#!/usr/bin/env python3
"""Rank the 169 Hold'em starting-hand classes by heads-up equity vs one random hand.

Method: Monte Carlo with this repo's engine; each class (all its combos, equally
weighted) vs 'random', SAMPLES per class, fixed SEED. Writes web/holdem-order.js.
Usage: python tools/holdem_order.py [--samples N] [--seed S] [--threads T]
"""
import argparse, os, sys, time
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from poker_engine import equity

RANKS = 'AKQJT98765432'

def classes():
    out = []
    for i, a in enumerate(RANKS):
        for j, b in enumerate(RANKS):
            if i == j: out.append(a + b)
            elif i < j: out += [a + b + 's', a + b + 'o']
    return out

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--samples', type=int, default=25_000_000)
    p.add_argument('--seed', type=int, default=42)
    p.add_argument('--threads', type=int, default=os.cpu_count() or 4)
    p.add_argument('--out', default=os.path.join(ROOT, 'web', 'holdem-order.js'))
    a = p.parse_args()
    t0 = time.time()
    eq = {}
    for c in classes():
        r = equity([c, 'random'], method='monte_carlo', samples=a.samples,
                   seed=a.seed, threads=a.threads)
        eq[c] = r.players[0].equity
    order = sorted(eq, key=lambda c: -eq[c])
    assert len(order) == 169 and len(set(order)) == 169
    el = time.time() - t0
    with open(a.out, 'w') as f:
        f.write(f"""// Generated by tools/holdem_order.py -- do not edit by hand.
// Preflop all-in equity of each of the 169 Hold'em starting-hand classes vs ONE
// uniformly random hand (heads-up), strongest first.
// Method: Monte Carlo, {a.samples:,} samples per class, seed {a.seed}, using poker_engine.
// Ties count as half. Stderr is at most {50 / a.samples ** 0.5:.3f} percentage points.
export const HOLDEM_ORDER = [{', '.join(repr(c) for c in order)}];
export const HOLDEM_EQUITY = {{{', '.join(f"'{c}': {eq[c]:.4f}" for c in order)}}};
""")
    print(f'{el:.0f}s', a.samples, a.seed)
    for i, c in enumerate(order): print(i + 1, c, f'{eq[c]:.4f}')

main()
